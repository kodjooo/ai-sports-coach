PROFILES = [
    dict(label="Новичок, зал, м, общая форма", goal="общая форма", sex="м", level="новичок",
         equip="всё оборудование зала", per_day=4, note="30 лет, здоров"),
    dict(label="Средний, дом (гантели+резинки), ж, похудение", goal="похудение", sex="ж", level="средний",
         equip="гантели, резинки", per_day=4, note="34 года, хочет сбросить вес"),
    dict(label="Продвинутый, зал, м, масса", goal="набор мышечной массы", sex="м", level="продвинутый",
         equip="всё оборудование зала", per_day=5, note="28 лет, 3 года стажа"),
    dict(label="Новичок, дом без инвентаря, ж, тонус, болит колено", goal="тонус и осанка", sex="ж", level="новичок",
         equip="коврик", per_day=3, note="40 лет, болит правое колено"),
    dict(label="Средний, улица турник/брусья, м, рельеф", goal="подтянуться и рельеф", sex="м", level="средний",
         equip="турник, брусья", per_day=4, note="26 лет"),
]


async def gen(p):
    main = catalog.main_candidates(p["equip"], p["level"])
    warm = catalog.warmup_candidates(p["equip"])
    usr = (f"Цель: {p['goal']}\nПол: {p['sex']}\nУровень: {p['level']}\n"
           f"Профиль: {p['note']}\nИнвентарь: {p['equip']}\nДни недели (0=Пн): [0,2,4]\n"
           f"На каждый день — РОВНО {p['per_day']} основных упражнений (exercises).\n\n"
           f"СПИСОК ОСНОВНЫХ (выбирай отсюда):\n{catalog.names_for_prompt(main)}\n\n"
           f"СПИСОК РАЗМИНКИ/ЗАМИНКИ (выбирай отсюда):\n{catalog.names_for_prompt(warm)}")
    c = llm.get_client().with_options(timeout=120.0, max_retries=0)
    r = await c.chat.completions.create(model="gpt-5.6-luna", reasoning_effort="low",
        response_format={"type": "json_object"},
        messages=[{"role": "system", "content": SYSTEM}, {"role": "user", "content": usr}])
    d = json.loads(r.choices[0].message.content or "{}")
    # сверка названий с палитрой
    out = {"progression": d.get("progression"), "workouts": []}
    for w in d.get("workouts", []):
        ex = []
        for e in w.get("exercises", []):
            hit = catalog.resolve_in(e.get("name", ""), main)
            if hit:
                ex.append({**e, "name": hit["name"], "muscle_group": hit["muscle_group"]})
        wu = [catalog.resolve_in(n, warm)["name"] for n in w.get("warmup", []) if catalog.resolve_in(n, warm)]
        cd = [catalog.resolve_in(n, warm)["name"] for n in w.get("cooldown", []) if catalog.resolve_in(n, warm)]
        out["workouts"].append({"weekday": w.get("weekday"), "warmup": wu, "cooldown": cd, "exercises": ex})
    return out


async def main():
    res = []
    for p in PROFILES:
        try:
            res.append({"profile": p["label"], "plan": await gen(p)})
        except Exception as e:
            res.append({"profile": p["label"], "error": str(e)[:120]})
    print("===LAB===")
    print(json.dumps(res, ensure_ascii=False))


asyncio.run(main())
